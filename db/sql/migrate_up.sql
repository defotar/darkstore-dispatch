-- Миграция схемы БД кластера v1 -> v2
\set ON_ERROR_STOP 1
\timing on

-- Шаг 1. Состояние «вручён» вместо поиска вручения в BundleItem
BEGIN;
INSERT INTO d01.OrderStatusDict VALUES (5, 'DELIVERED', 'Вручён');
UPDATE d01.DeliveryOrder o SET order_status_id = 5
  FROM d04.BundleItem bi WHERE bi.order_id = o.order_id AND bi.deliver_fact_dttm IS NOT NULL;
ALTER TABLE d01.DeliveryOrder ADD CONSTRAINT deliveryorder_ready_ck
  CHECK (order_status_id NOT IN (2, 5) OR ready_fact_dttm IS NOT NULL) NOT VALID;
COMMIT;
ALTER TABLE d01.DeliveryOrder VALIDATE CONSTRAINT deliveryorder_ready_ck;

-- Шаг 2. Индексы под типовые запросы; после шага 1, чтобы частичный индекс не содержал вручённых заказов; без блокировки записи
CREATE INDEX CONCURRENTLY deliveryorder_active_ix ON d01.DeliveryOrder (subzone_id, deadline_dttm) WHERE order_status_id IN (1, 2, 4);
CREATE INDEX CONCURRENTLY bundleitem_bundle_ix ON d04.BundleItem (bundle_id, item_ord);
CREATE INDEX CONCURRENTLY bundleitem_order_ix ON d04.BundleItem (order_id);
CREATE INDEX CONCURRENTLY arrival_darkstore_ix ON d03.Arrival (darkstore_id, arrive_dttm);
CREATE INDEX CONCURRENTLY direction_target_ix ON d04.Direction (target_darkstore_id, issue_dttm);

-- Шаг 3. Соседство подзон: одна запись на пару
BEGIN;
INSERT INTO d01.SubzoneNeighborLink
  SELECT neighbor_subzone_id, subzone_id FROM d01.SubzoneNeighborLink WHERE subzone_id > neighbor_subzone_id
  ON CONFLICT DO NOTHING;
DELETE FROM d01.SubzoneNeighborLink WHERE subzone_id > neighbor_subzone_id;
ALTER TABLE d01.SubzoneNeighborLink DROP CONSTRAINT subzoneneighborlink_check,
  ADD CONSTRAINT subzoneneighborlink_order_ck CHECK (subzone_id < neighbor_subzone_id);
COMMIT;

-- Шаг 4. Точность прогнозов: строка на тип прогноза
BEGIN;
CREATE TABLE d05.ForecastTypeDict (
  forecast_type_id BIGINT PRIMARY KEY, forecast_type_code VARCHAR(64) NOT NULL UNIQUE,
  forecast_type_name VARCHAR(256) NOT NULL);
INSERT INTO d05.ForecastTypeDict VALUES (1, 'READY', 'Готовность заказа'), (2, 'RELEASE', 'Освобождение курьера'), (3, 'SUPPLY', 'Подача курьера');
ALTER TABLE d05.ForecastAccuracy RENAME TO ForecastAccuracy_v1;
CREATE TABLE d05.ForecastAccuracy (
  accuracy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  darkstore_id BIGINT NOT NULL REFERENCES d01.Darkstore,
  calc_dt DATE NOT NULL, forecast_type_id BIGINT NOT NULL REFERENCES d05.ForecastTypeDict,
  error_sec INTEGER NOT NULL, UNIQUE (darkstore_id, calc_dt, forecast_type_id));
INSERT INTO d05.ForecastAccuracy (darkstore_id, calc_dt, forecast_type_id, error_sec)
  SELECT darkstore_id, calc_dt, t.id, t.v FROM d05.ForecastAccuracy_v1,
    LATERAL (VALUES (1, ready_error_sec), (2, release_error_sec), (3, supply_error_sec)) t(id, v);
COMMIT;

-- Шаг 5. Журнал решений без разделов; DecisionOption без копии log_dttm
BEGIN;
ALTER TABLE d05.DecisionLog RENAME TO DecisionLog_v1;
CREATE TABLE d05.DecisionLog (
  decision_log_id BIGINT PRIMARY KEY, direction_id BIGINT NOT NULL REFERENCES d04.Direction,
  parameter_id BIGINT NOT NULL REFERENCES d04.DistributionParameter,
  log_dttm TIMESTAMPTZ NOT NULL, decision_reason_desc TEXT);
INSERT INTO d05.DecisionLog SELECT decision_log_id, direction_id, parameter_id, log_dttm, decision_reason_desc FROM d05.DecisionLog_v1;
CREATE INDEX decisionlog_direction_ix ON d05.DecisionLog (direction_id);
CREATE INDEX decisionlog_log_ix ON d05.DecisionLog (log_dttm);
ALTER TABLE d05.DecisionOption DROP CONSTRAINT decisionoption_decision_log_id_log_dttm_fkey,
  ADD CONSTRAINT decisionoption_decision_log_fk FOREIGN KEY (decision_log_id) REFERENCES d05.DecisionLog;
COMMIT;

-- Шаг 6. Согласованность состояния и фактов
ALTER TABLE d04.Bundle ADD CONSTRAINT bundle_depart_ck
  CHECK ((depart_fact_dttm IS NULL) = (bundle_status_id IN (1, 4))) NOT VALID;
ALTER TABLE d04.Bundle VALIDATE CONSTRAINT bundle_depart_ck;
ALTER TABLE d04.Direction ADD CONSTRAINT direction_target_ck
  CHECK (change_fact_dttm IS NOT NULL OR target_darkstore_id = initial_darkstore_id) NOT VALID;
ALTER TABLE d04.Direction VALIDATE CONSTRAINT direction_target_ck;

-- Шаг 7. Сжатие (после проверки и периода наблюдения): удаление выводимых столбцов и старых таблиц
BEGIN;
ALTER TABLE d01.DeliveryOrder DROP CONSTRAINT deliveryorder_check,
  ADD CONSTRAINT deliveryorder_deadline_ck CHECK (deadline_dttm > place_dttm);
ALTER TABLE d01.DeliveryOrder DROP COLUMN promise_sec, DROP COLUMN overdue_bool;
ALTER TABLE d05.DecisionOption DROP COLUMN log_dttm;
DROP TABLE d05.DecisionLog_v1;
DROP TABLE d05.ForecastAccuracy_v1;
COMMIT;
ANALYZE;
